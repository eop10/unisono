//! Окно анализа и границы поиска периода (docs/source/04_dsp.md, 4.2).
//!
//! Размер окна выбирается реестром по нижней ноте строя
//! (`music::InstrumentRegistry::window_size`, ADR-006/ADR-009); здесь —
//! пересчёт границ τ от фактической частоты дискретизации и цели.

/// Допустимые окна анализа (отсчёты).
pub const WINDOWS: [u32; 3] = [4096, 8192, 16384];

/// Верхняя граница диапазона определения (Гц), ФТ-02.
pub const F_MAX_HZ: f32 = 1400.0;
/// Нижняя граница диапазона определения при A4 = 440 (Гц), ФТ-02.
pub const F_MIN_HZ: f32 = 30.0;

/// `τ_min = fs / 1400`, не меньше 2 (4.2.1).
pub fn tau_min(fs: u32) -> usize {
    ((fs as f32 / F_MAX_HZ) as usize).max(2)
}

/// `τ_max = fs / (0.94 · f_min)`, но не больше `window / 2`.
///
/// `f_min` — фактическая нижняя целевая частота при текущей A4, а не константа
/// из таблицы: запас 0,94 покрывает расстройку струны вниз. Значения 686/780/1600
/// из 4.2.3 — иллюстрация для 48 кГц, не хардкод.
pub fn tau_max(fs: u32, f_min_hz: f32, window: usize) -> usize {
    let t = (fs as f32 / (0.94 * f_min_hz)) as usize;
    t.min(window / 2).max(tau_min(fs) + 1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tau_min_covers_1400_hz() {
        assert_eq!(tau_min(48_000), 34);
        assert_eq!(tau_min(44_100), 31);
        assert_eq!(tau_min(8_000), 5);
        assert_eq!(tau_min(100), 2);
    }

    #[test]
    fn tau_max_from_actual_target() {
        // E2 при 440: 48000 / (0.94 · 82.41) ≈ 619.
        assert_eq!(tau_max(48_000, 82.41, 4096), 619);
        // B0 при 440: 48000 / (0.94 · 30.87) ≈ 1654, окно 16384 не режет.
        assert_eq!(tau_max(48_000, 30.87, 16384), 1654);
        // При A4 = 400 цель B0 = 28.06 Гц: τ растёт, но не выше window/2.
        assert_eq!(tau_max(48_000, 28.06, 16384), 1819);
        // Ниже 6,24 Гц сработал бы потолок window/2.
        assert_eq!(tau_max(48_000, 5.0, 16384), 8192);
    }

    #[test]
    fn tau_max_rescales_with_fs() {
        // 44,1 кГц: все границы пересчитываются, не фиксированы в семплах (4.7).
        assert_eq!(tau_max(44_100, 82.41, 4096), 569);
        assert!(tau_max(44_100, 30.87, 16384) < tau_max(48_000, 30.87, 16384));
    }
}
